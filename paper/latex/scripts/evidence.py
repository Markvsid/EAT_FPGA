"""Deterministic tables from saved evidence; standard library only."""
import csv
import hashlib
import io
import json
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
REPOSITORY = PROJECT.parents[1]
ACCURACY_SOURCE = Path('results/software_release_v1/accuracy.csv')
ARCHIVE = Path('rtl/validation/implementation_v2')
CORE_REPORTS = [
    'core_counter_check_results.json', 'final_core_har_quality_results.json',
    'final_core_har_balanced_results.json', 'final_core_speech_quality_results.json',
    'final_core_speech_balanced_results.json', 'final_core_speech_energy_results.json',
    'final_stress_checker_results.json', 'final_stress_max_results.json',
    'final_stress_min_results.json', 'final_stress_speech_results.json',
]
SYSTEM_REPORTS = ['system_energy_results.json', 'system_balanced_results.json', 'system_speech_results.json']


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def accuracy_table(content):
    rows = list(csv.DictReader(io.StringIO(content)))
    selected = {(r['dataset'], r['mode']): r for r in rows
                if r['family'] == 'independent' and r['partition'] == 'test'}
    assert len(selected) == 6, 'Expected six independent test aggregates'
    lines = [r'% Generated by scripts/refresh_evidence.py; edit the source evidence instead.',
             r'\begin{table}',
             r'\caption{Preliminary Python test accuracy (percent), mean $\pm$ sample SD over three seeds. These are subsequent evaluations on previously observed test sets.}',
             r'\label{tab:software-accuracy}', r'\centering',
             r'\begin{tabular}{llc}', r'\toprule',
             r'Workload & Mode & Accuracy (\%) \\', r'\midrule']
    for dataset, label in [('har', 'HAR'), ('speech', 'Speech Commands')]:
        if dataset == 'speech':
            lines.append(r'\midrule')
        for mode, title in [('quality', 'Quality'), ('balanced', 'Balanced'), ('energy_saver', 'Energy-Saver')]:
            row = selected[(dataset, mode)]
            value, sd = float(row['accuracy_percent']), float(row['accuracy_sd_points'])
            assert 0 <= value <= 100 and sd >= 0
            lines.append(f'{label} & {title} & ${value:.3f} \\pm {sd:.3f}$ ' + r'\\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    return '\n'.join(lines)


def rtl_summary():
    core, system, sources = [], [], {}
    for name in CORE_REPORTS + SYSTEM_REPORTS:
        source = REPOSITORY / ARCHIVE / name
        report = json.loads(source.read_text())
        assert report['status'] == 'passed', source
        sources[str(ARCHIVE / name)] = sha256(source)
        (core if name in CORE_REPORTS else system).extend(report['cases'])
    result = {
        'status': 'archived_local_simulations_only',
        'core_cases': len(core), 'core_logits': sum(c['exact_logits'] for c in core),
        'platform_inferences': sum(c['inferences'] for c in system),
        'platform_logits': sum(c['inferences'] * c['exact_logits_per_inference'] for c in system),
        'source_report_sha256': sources,
    }
    assert (result['core_cases'], result['core_logits'], result['platform_inferences'], result['platform_logits']) == (10, 176, 4, 53)
    return result


