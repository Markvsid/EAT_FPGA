    return '\n'.join([
        r'% Generated from archived RTL reports by scripts/refresh_evidence.py.',
        r'\begin{table}',
        r'\caption{Selected complete-inference RTL simulations. All listed integer logits match. These counts do not establish full-dataset or board equivalence.}',
        r'\label{tab:rtl-coverage}', r'\centering',
        r'\begin{tabular}{lrr}', r'\toprule',
        r'Boundary & Inferences & Checked logits \\', r'\midrule',
        f"Core with simulated services & {summary['core_cases']} & {summary['core_logits']} " + r'\\',
        f"Loaded AXI peripheral & {summary['platform_inferences']} & {summary['platform_logits']} " + r'\\',
        r'\bottomrule', r'\end{tabular}', r'\end{table}', '',
    ])
