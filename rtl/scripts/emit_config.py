"""Generate draft HDL constants from existing numerical and RTL proposals."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate():
    numeric_path = ROOT / 'config/numerics.json'
    rtl_path = ROOT / 'rtl/config/rtl_candidate.json'
    n, c = json.loads(numeric_path.read_text()), json.loads(rtl_path.read_text())
    values = {'NUMERIC_VERSION': n['version'], 'STATE_BITS': n['state_signed_bits'], 'STATE_FRAC': n['state_fraction_bits'],
              'ACT_BITS': n['linear_activation_signed_bits'], 'ACC_BITS': n['linear_accumulator_signed_bits'],
              'MULT_BITS': c['multiplier_signed_bits_candidate'], 'MULT_FRAC': n['weight_multiplier_fraction_bits'],
              'GAMMA_BITS': c['gamma_signed_bits'], 'GAMMA_FRAC': n['norm_gamma_fraction_bits'],
              'NORM_EPSILON_Q24': n['norm_epsilon_q24'], 'EXP_FRAC': n['exp_fraction_bits'],
              'EXP_BITS': n['exp_fraction_bits'] + 1, 'EXP_ADDR_BITS': 13, 'RSQRT_ADDR_BITS': 10,
              'ATTENTION_TILE': n['attention_tile'], 'QK_ACC_BITS': c['qk_accumulator_signed_bits'],
              'SCORE_BITS': c['attention_score_signed_bits_candidate'], 'AV_ACC_BITS': c['attention_value_accumulator_signed_bits'],
              'NORMALIZER_BITS': c['attention_normalizer_signed_bits'], 'GROUP_SCORE_BITS': c['group_score_signed_bits'],
              'SUMMARY_NUM_BITS': c['summary_numerator_signed_bits'], 'LANES': c['lanes'],
              'ARRAY_ROWS': c['array_rows'], 'ARRAY_COLS': c['array_columns'], 'AXIS_BITS': c['axis_bits'],
              'AXIL_ADDR_BITS': c['axi_lite_address_bits'], 'AXIL_DATA_BITS': c['axi_lite_data_bits'],
              'MEM_ADDR_BITS': c['memory_address_bits'], 'MODEL_BANKS': c['model_banks_candidate'],
              'MAX_TOKENS': c['maximum_tokens'], 'MAX_MATRIX_COLS': c['maximum_matrix_columns'],
              'MAX_REDUCTION': c['maximum_reduction'], 'WIDTH': 128, 'HEADS': 4, 'LAYERS': 4,
              'GROUP_SIZE': 4, 'FFN_WIDTH': 256, 'MAX_CLASSES': 35}
    lines = ['-- Generated by rtl/scripts/emit_config.py. Proposed ABI, not hardware approval.',
             '-- numeric SHA256: ' + hashlib.sha256(numeric_path.read_bytes()).hexdigest(),
             '-- RTL proposal SHA256: ' + hashlib.sha256(rtl_path.read_bytes()).hexdigest(),
             'library ieee;', 'use ieee.std_logic_1164.all;', '', 'package eat_config_pkg is']
    lines += [f'  constant C_{key} : natural := {value};' for key, value in values.items()]
    lines += ['end package;', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'rtl/pkg/eat_config_pkg.vhd'
    text = generate()
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('Generated HDL configuration is stale')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


if __name__ == '__main__':
    main()
