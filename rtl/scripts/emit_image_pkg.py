"""Generate the agreed logical image map; physical placement is separate."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def render():
 s=json.loads((ROOT/'rtl/config/image_schema.json').read_text())
 lines=['-- Generated by emit_image_pkg.py from image_schema.json. ABI2 logical words.','library ieee;use ieee.std_logic_1164.all;use ieee.numeric_std.all;','use work.eat_config_pkg.all;use work.eat_types_pkg.all;','package eat_image_pkg is',f"  constant C_IMAGE_BANK_WORDS : positive := {s['bank_words']};",f"  constant C_IMAGE_PROFILE_WORDS : positive := {s['profile_words']};",f"  constant C_IMAGE_MAGIC : unsigned(31 downto 0) := x\"{s['magic']:08x}\";",'  function region_offset(kind:constant_kind_t) return natural;','  function region_words(kind:constant_kind_t) return positive;','  function image_address(kind:constant_kind_t;bank:bank_id_t;offset:mem_addr_t) return mem_addr_t;','end package;','package body eat_image_pkg is']
 for function,key,typ in [('region_offset','offset','natural'),('region_words','words','positive')]:
  lines += [f'  function {function}(kind:constant_kind_t) return {typ} is','  begin case kind is']
  lines += [f"    when CONST_{r['kind']} => return {r[key]};" for r in s['regions']]
  lines += ['  end case;end;']
 lines += ['  function image_address(kind:constant_kind_t;bank:bank_id_t;offset:mem_addr_t) return mem_addr_t is','  begin return to_unsigned(to_integer(bank)*C_IMAGE_BANK_WORDS+region_offset(kind)+to_integer(offset),C_MEM_ADDR_BITS);end;','end package body;','']
 return '\n'.join(lines)
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--output',type=Path,default=ROOT/'rtl/pkg/eat_image_pkg.vhd');a=p.parse_args();text=render()
 if a.check:
  if a.output.read_text()!=text:raise SystemExit('Stale image package')
 else:a.output.write_text(text)
if __name__=='__main__':main()
